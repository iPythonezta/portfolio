import { chromium } from "playwright";
const out = process.argv[2];
const b = await chromium.launch({ channel: "chrome" });
const ctx = await b.newContext({ viewport: { width: 1280, height: 800 } });
const page = await ctx.newPage();
const errs = []; page.on("pageerror", (e) => errs.push(String(e))); page.on("console", (m) => m.type() === "error" && errs.push(m.text()));
await page.goto("http://localhost:3100/", { waitUntil: "networkidle" });
await page.waitForTimeout(6000); // let hero typing finish
await page.screenshot({ path: `${out}/hero-done.png` });
await page.keyboard.press("Control+k");
await page.keyboard.type("big");
await page.waitForTimeout(300);
await page.screenshot({ path: `${out}/palette.png` });
await page.keyboard.press("Enter");
await page.waitForURL("**/projects/bigsearch");
console.log("palette navigated to", page.url());
await page.goto("http://localhost:3100/#about", { waitUntil: "networkidle" });
await page.fill("#term-input", "ls projects"); await page.keyboard.press("Enter");
await page.fill("#term-input", "foo"); await page.keyboard.press("Enter");
await page.waitForTimeout(300);
const t = await page.locator("#about").innerText();
console.log("terminal shows ls output:", t.includes("zerodevai"), "| error line:", t.includes("command not found"));
await page.click("text=theme >> nth=0");
console.log("theme after toggle:", await page.evaluate(() => document.documentElement.dataset.theme));
const m = await ctx.newPage(); await m.setViewportSize({ width: 390, height: 844 });
await m.goto("http://localhost:3100/#projects", { waitUntil: "networkidle" }); await m.waitForTimeout(1200);
await m.screenshot({ path: `${out}/mobile-projects.png` });
const r = await b.newContext({ viewport: { width: 1280, height: 800 }, reducedMotion: "reduce" });
const rp = await r.newPage(); await rp.goto("http://localhost:3100/", { waitUntil: "networkidle" }); await rp.waitForTimeout(500);
console.log("reduced-motion hero has full text immediately:", (await rp.locator("section").first().innerText()).includes("2022"));
console.log("errors:", errs.length ? errs : "none");
await b.close();
